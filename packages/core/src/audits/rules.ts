/**
 * Declarative audit rules. Each rule is SQL over the per-crawl schema (schema.ts):
 * - `page` rules are a WHERE clause over `pages p`. The Crawl DO applies them to each ingested
 *   batch, so issue counts update live while the crawl runs.
 * - `crawl` rules need the whole crawl (duplicates, link graph, hreflang reciprocity). They are a
 *   full `SELECT <url id>` and run once, during analysis.
 * - `computed` rules are filled in by analysis code (redirect loops, near-duplicates).
 */

export type Severity = 'issue' | 'warning' | 'opportunity';
export type Priority = 'high' | 'medium' | 'low';

export type TabId =
  | 'response-codes'
  | 'security'
  | 'url'
  | 'titles'
  | 'meta-description'
  | 'h1'
  | 'h2'
  | 'content'
  | 'images'
